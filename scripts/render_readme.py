"""Render the README results from results/metrics.json.

    python scripts/render_readme.py          rewrite the generated blocks
    python scripts/render_readme.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
ORDER = ["Cointegration", "Distance", "All pairs"]


def diff(m, a, b, kind):
    return next(d for d in m["differences"] if d["a"] == a and d["b"] == b and d["returns"] == kind)


def headline(m: dict) -> str:
    s, p, sc, pe = m["sample"], m["portfolios"], m["screen"], m["persistence"]
    co, al = p["Cointegration"], p["All pairs"]
    d = diff(m, "Cointegration", "All pairs", "net")
    checks = {
        "the cointegration portfolio's net return is not significant": abs(co["net"]["t"]) < 1.96,
        "its gross Sharpe ratio is below 0.2": co["gross"]["sharpe"] < 0.2,
        "it beats trading every pair, significantly": d["t"] > 1.96,
        "trading every pair loses money": al["net"]["ann_return"] < 0,
        "the screen passes more pairs than chance": sc["mean_pass_5pct"] > sc["expected_by_chance"],
        "selected pairs pass again only slightly more often": 0 < pe["selected_pass_rate"] - pe["all_pairs_pass_rate"] < 0.05,
        "fewer than half of the trades converge": co["converged_share"] < 0.5,
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_readme.py. Failed: " + "; ".join(failed))
    return (
        f"**Answer, over {s['n_periods']} formation and trading periods from {s['first_day'][:4]} to "
        f"{s['last_day'][:4]}: barely, and not enough to trade.** The ten most cointegrated pairs of each "
        f"period earn {co['gross']['ann_return']:.1%} a year before costs and {co['net']['ann_return']:.1%} "
        f"after (Sharpe ratio {co['gross']['sharpe']:.2f} and {co['net']['sharpe']:.2f}, neither "
        f"distinguishable from zero). The screen is not worthless: it beats trading every pair by "
        f"{d['ann_diff']:.1%} a year (t = {d['t']:.1f}), because trading every pair loses money. But the "
        f"property it selects on does not last. A pair picked by the screen is still cointegrated in the "
        f"next two years {pe['selected_pass_rate']:.0%} of the time, against {pe['all_pairs_pass_rate']:.0%} "
        f"for any pair, and only {co['converged_share']:.0%} of the trades it opens converge before the "
        f"period ends."
    )


def results(m: dict) -> str:
    s, p, sc, pe = m["sample"], m["portfolios"], m["screen"], m["persistence"]
    out = [f"Daily returns {s['first_day']} to {s['last_day']} ({s['years']:.0f} years, {s['n_periods']} periods of "
           f"{s['trading']} trading days, each formed on the {s['formation']} days before it). On average "
           f"{s['pairs_tested_mean']:.0f} within-sector pairs are tested per period. Returns are on committed "
           f"capital; costs are {s['cost_bps']:.0f} bps per unit traded per leg; t-statistics use Newey-West errors.",
           "", "| Portfolio | Return per year, gross | Sharpe, gross | Return per year, net | Sharpe, net | t, net | "
           "Max drawdown | Trades that converge |", "|---|---|---|---|---|---|---|---|"]
    for k in ORDER:
        g, n = p[k]["gross"], p[k]["net"]
        out.append(f"| {k} | {g['ann_return']:+.2%} | {g['sharpe']:+.2f} | {n['ann_return']:+.2%} | "
                   f"{n['sharpe']:+.2f} | {n['t']:+.2f} | {n['max_drawdown']:.0%} | {p[k]['converged_share']:.0%} |")
    out += ["", "**Does selection help?** Difference in annual return, with its t-statistic", "",
            "| Comparison | Gross | Net |", "|---|---|---|"]
    for a, b in (("Cointegration", "All pairs"), ("Distance", "All pairs"), ("Cointegration", "Distance")):
        g, n = diff(m, a, b, "gross"), diff(m, a, b, "net")
        out.append(f"| {a} minus {b.lower()} | {g['ann_diff']:+.2%} ({g['t']:+.2f}) | "
                   f"{n['ann_diff']:+.2%} ({n['t']:+.2f}) |")
    eras = list(p["Cointegration"]["eras"])
    out += ["", "**Net Sharpe ratio by era**", "", "| Portfolio | " + " | ".join(eras) + " |",
            "|---|" + "---|" * len(eras)]
    for k in ORDER:
        out.append(f"| {k} | " + " | ".join(f"{p[k]['eras'][e]['net']:+.2f}" for e in eras) + " |")
    out += ["", f"**The screen itself.** On average {sc['mean_pass_5pct']:.1f} pairs per period pass the "
            f"Engle-Granger test at 5%, where {sc['expected_by_chance']:.1f} would pass by chance alone; the "
            f"count is above chance in {sc['share_of_periods_above_chance']:.0%} of periods. Of the ten pairs "
            f"selected in a period, {pe['selected_pass_rate']:.1%} pass the same test on the following, "
            f"non-overlapping 24 months. For all pairs the figure is {pe['all_pairs_pass_rate']:.1%} "
            f"({pe['periods']} periods)."]
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "headline", headline(m)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
